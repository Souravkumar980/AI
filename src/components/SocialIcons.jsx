/**
 * Identify platform from a URL string and return appropriate icon and style
 */
export function getSocialPlatformInfo(url = '') {
  const str = String(url).toLowerCase();
  if (str.includes('twitter.com') || str.includes('x.com')) {
    return { name: 'X / Twitter', icon: TwitterIcon, bgClass: 'bg-black text-white hover:bg-gray-800' };
  }
  if (str.includes('youtube.com') || str.includes('youtu.be')) {
    return { name: 'YouTube', icon: YoutubeIcon, bgClass: 'bg-red-600 text-white hover:bg-red-700' };
  }
  if (str.includes('instagram.com')) {
    return { name: 'Instagram', icon: InstagramIcon, bgClass: 'bg-gradient-to-r from-purple-600 via-pink-600 to-amber-500 text-white' };
  }
  if (str.includes('facebook.com') || str.includes('fb.watch') || str.includes('fb.me')) {
    return { name: 'Facebook', icon: FacebookIcon, bgClass: 'bg-[#1877F2] text-white hover:bg-blue-700' };
  }
  if (str.includes('pinterest.com') || str.includes('pin.it')) {
    return { name: 'Pinterest', icon: PinterestIcon, bgClass: 'bg-[#BD081C] text-white hover:bg-red-800' };
  }
  if (str.includes('linkedin.com')) {
    return { name: 'LinkedIn', icon: LinkedinIcon, bgClass: 'bg-[#0A66C2] text-white hover:bg-blue-800' };
  }
  if (str.includes('t.me') || str.includes('telegram.org')) {
    return { name: 'Telegram', icon: TelegramIcon, bgClass: 'bg-[#229ED9] text-white hover:bg-sky-600' };
  }
  return { name: 'Website', icon: GlobeIcon, bgClass: 'bg-gray-800 text-white hover:bg-black' };
}
